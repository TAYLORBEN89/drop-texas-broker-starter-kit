// Run: node cpp/generate-tables.mjs
import fs from 'node:fs';
import * as H from '../js/drop-hash.mjs';
const MAX = 0x10ffff;
const isSur = (cp) => cp >= 0xd800 && cp <= 0xdfff;
const lit = (s) => '"' + [...Buffer.from(s, 'utf8')].map((b) => '\\x' + b.toString(16).padStart(2, '0')).join('') + '"';
const lower = [], nameMap = [], nameDrop = [], ln = [], cased = [], ignorable = [];
const pushRange = (arr, cp) => { const l = arr[arr.length - 1]; if (l && l[1] === cp - 1) l[1] = cp; else arr.push([cp, cp]); };
for (let cp = 0; cp <= MAX; cp++) {
  if (isSur(cp)) continue;
  const c = String.fromCodePoint(cp);
  const lc = c.toLowerCase();
  if (lc !== c) lower.push([cp, lc]);
  if (/[\p{L}\p{N}]/u.test(c)) pushRange(ln, cp);
  if (/\p{Cased}/u.test(c)) pushRange(cased, cp);
  if (/\p{Case_Ignorable}/u.test(c)) pushRange(ignorable, cp);
  const n = H.stdName(c) ?? '';
  if (n === '') pushRange(nameDrop, cp);
  else if (n !== c) nameMap.push([cp, n]);
}
let o = `// SPDX-License-Identifier: Apache-2.0\n// Copyright DROP Texas contributors\n// GENERATED by cpp/generate-tables.mjs from js/drop-hash.mjs with Unicode ${process.versions.unicode}. Do not edit.\n`;
o += `static const CpStr LOWER_MAP[] = {\n${lower.map(([c, s]) => `{0x${c.toString(16)},${lit(s)}}`).join(',\n')}\n};\n`;
o += `static const CpStr NAME_MAP[] = {\n${nameMap.map(([c, s]) => `{0x${c.toString(16)},${lit(s)}}`).join(',\n')}\n};\n`;
o += `static const CpRange NAME_DROP[] = {\n${nameDrop.map(([a, b]) => `{0x${a.toString(16)},0x${b.toString(16)}}`).join(',\n')}\n};\n`;
o += `static const CpRange LETTER_OR_NUMBER[] = {\n${ln.map(([a, b]) => `{0x${a.toString(16)},0x${b.toString(16)}}`).join(',\n')}\n};\n`;
o += `static const CpRange CASED[] = {\n${cased.map(([a, b]) => `{0x${a.toString(16)},0x${b.toString(16)}}`).join(',\n')}\n};\n`;
o += `static const CpRange CASE_IGNORABLE[] = {\n${ignorable.map(([a, b]) => `{0x${a.toString(16)},0x${b.toString(16)}}`).join(',\n')}\n};\n`;
fs.writeFileSync(new URL('./drop_tables.inc', import.meta.url), o);
console.log({ lower: lower.length, nameMap: nameMap.length, nameDrop: nameDrop.length, ln: ln.length, cased: cased.length, ignorable: ignorable.length });
