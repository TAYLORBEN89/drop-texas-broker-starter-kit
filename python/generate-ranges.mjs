// Generates python/_unchanged_ranges.py from js/drop-hash.mjs (the JS reference is the source of truth).
// Python's unicodedata has no Script property, so the code point ranges are generated here. Run: node python/generate-ranges.mjs
import fs from 'node:fs';
import { UNCHANGED_SCRIPTS } from '../js/drop-hash.mjs';
const re = new RegExp(`[${UNCHANGED_SCRIPTS.map((s) => `\\p{Script=${s}}`).join('')}]`, 'u');
const r = [];
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  if (!re.test(String.fromCodePoint(cp))) continue;
  const l = r[r.length - 1];
  if (l && l[1] === cp - 1) l[1] = cp; else r.push([cp, cp]);
}
const hx = (n) => '0x' + n.toString(16).toUpperCase().padStart(4, '0');
let o = `# SPDX-License-Identifier: Apache-2.0\n# Copyright DROP Texas contributors\n# GENERATED by python/generate-ranges.mjs from js/drop-hash.mjs with Unicode ${process.versions.unicode}. Do not edit.\n`;
o += `# Code points in the scripts the CPPA DROP spec leaves unchanged: ${UNCHANGED_SCRIPTS.join(', ')}.\n`;
o += 'UNCHANGED_RANGES = (\n' + r.map(([a, b]) => `    (${hx(a)}, ${hx(b)}),`).join('\n') + '\n)\n';
fs.writeFileSync(new URL('./_unchanged_ranges.py', import.meta.url), o);
console.log(r.length);
